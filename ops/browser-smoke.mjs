// Browser verification uses a synthetic database and never accepts an external API URL.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';
import { chromium } from '../frontend/node_modules/playwright/index.mjs';
import { disposableBackend, runFixture, startFixture } from '../backend/tests/helpers/disposable.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const report = path.join(root, 'artifacts/browser');
fs.mkdirSync(report, { recursive: true });
const fixture = disposableBackend();
const temporary = 'Synthetic-' + randomBytes(20).toString('hex') + '!';
const personal = 'Personal-' + randomBytes(20).toString('hex') + '!';
const pdf = Buffer.from('%PDF-1.4\n1 0 obj\n<< /Type /Catalog >>\nendobj\ntrailer\n<< /Root 1 0 R >>\n%%EOF');
let running, browser;
const checks = [];
try {
  fs.rmSync(path.join(fixture.root, 'frontend/dist'), { recursive: true });
  fs.symlinkSync(path.join(root, 'frontend/dist'), path.join(fixture.root, 'frontend/dist'), 'dir');
  const setup = runFixture(fixture, `import {getStore,saveStore,db,DOC_TEMPLATE} from './src/db/database.js';
import {hashPassword} from './src/security/passwords.js';
import fs from 'node:fs';
const state=getStore();
state.users=[{id:'fixture-super',name:'Operator Uji Sintetis',email:'operator@example.test',role:'super_admin',branch:'BANDUNG',bank_scope:'all_bank',active:true,auth_version:1,must_change_password:true,password_hash:await hashPassword(fs.readFileSync(0,'utf8'))}];
state.applications=[{...state.applications[0],id:'fixture-app',app_no:'APP-UJI',lead_name:'Nasabah Sintetis',stage:'upload_dokumen',rejected:false,history:[],stage_data:{},pending:{party:'admin_ops',type:'pemeriksaan'},checklist:DOC_TEMPLATE.map(d=>({...d,status:null,versions:0,filename:null}))}];
state.claims=[{...state.claims[0],id:'fixture-claim',claim_no:'KLAIM-UJI',lead_name:'Nasabah Sintetis',amount:250000,status:'SUBMITTED',paid_at:null,paid_by:null,history:[]}];
state.leads=[];state.lead_requests=[];state.imports=[];state.parameter_proposals=[];state.audit_logs=[];state.simulations=[];
saveStore();db.close();`, 'development', temporary);
  assert.equal(setup.status, 0, setup.stderr);
  running = await startFixture(fixture, 'production');
  browser = await chromium.launch(process.argv.includes('--system-chromium') ? { executablePath: '/usr/bin/chromium', headless: true } : { headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, serviceWorkers: 'block' });
  await context.route('**/*', async route => {
    const url = route.request().url();
    if (url.startsWith(running.base) || url.startsWith('blob:') || url.startsWith('data:')) await route.continue(); else await route.abort();
  });
  await context.addInitScript(() => sessionStorage.setItem('lp_bypass_pwa', '1'));
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept('Dokumen tidak terbaca, mohon unggah ulang.'));
  await page.goto(running.base + '/login?demo=1');
  await page.getByTestId('login-email-input').waitFor();
  assert.equal(await page.getByTestId('login-email-input').inputValue(), '');
  assert.equal(await page.getByTestId('login-password-input').inputValue(), '');
  assert.equal(await page.getByTestId('quick-role-panel').count(), 0);
  await page.getByTestId('login-email-input').fill('operator@example.test');
  await page.getByTestId('login-password-input').fill(temporary);
  await page.getByTestId('login-submit-button').click();
  await page.getByTestId('password-change-gate').waitFor();
  await page.locator('#initial-current').fill(temporary);
  await page.locator('#initial-new').fill(personal);
  await page.locator('#initial-confirm').fill(personal);
  await page.getByRole('button', { name: 'Simpan dan lanjutkan' }).click();
  await page.getByTestId('nav-pengaturan').waitFor();
  checks.push('production login has no demo credentials; first-login password gate completes');
  await page.getByTestId('nav-pengaturan').click();
  await page.getByTestId('restore-button').waitFor();
  assert.equal(await page.getByTestId('restore-button').isDisabled(), true);
  await page.screenshot({ path: path.join(report, 'settings-production.png'), fullPage: true });
  checks.push('production settings render; browser restore is disabled');
  await page.getByTestId('nav-progress').click();
  await page.getByTestId('progress-row-fixture-app').click();
  await page.getByTestId('doc-checklist').waitFor();
  const chooserPromise = page.waitForEvent('filechooser');
  await page.getByTestId('upload-ktp_pasangan').click();
  const chooser = await chooserPromise;
  await chooser.setFiles({ name: 'berkas-uji.pdf', mimeType: 'application/pdf', buffer: pdf });
  const row = page.getByTestId('doc-row-ktp_pasangan');
  await row.getByRole('button', { name: 'berkas-uji.pdf' }).waitFor();
  await page.getByTestId('accept-ktp_pasangan').click();
  await page.getByText('Buka dan periksa berkas terbaru sebelum menyetujui.').waitFor();
  const opened = context.waitForEvent('page');
  await row.getByRole('button', { name: 'berkas-uji.pdf' }).click();
  const preview = await opened; await preview.close();
  const accepted = page.waitForResponse(response => response.url().endsWith('/ktp_pasangan/review') && response.request().method() === 'POST', { timeout: 5000 });
  await page.getByTestId('accept-ktp_pasangan').click();
  assert.equal((await accepted).status(), 200);
  await row.getByText('DITERIMA', { exact: true }).waitFor();
  assert.equal(await page.getByTestId('doc-row-kk').getByText('KOSONG', { exact: true }).count(), 1);
  await page.screenshot({ path: path.join(report, 'individual-document-review.png'), fullPage: true });
  checks.push('a document needs opening before acceptance; accepting one leaves other documents pending');
  await page.keyboard.press('Escape');
  await page.getByTestId('nav-klaim').click();
  await page.getByTestId('claim-row-fixture-claim').click();
  await page.getByTestId('claim-approve').click();
  await page.getByTestId('claim-file-input').waitFor();
  await page.getByTestId('claim-detail-dialog').getByText('APPROVED', { exact: true }).first().waitFor();
  assert.equal(await page.getByTestId('claim-detail-dialog').getByText(/^Dibayar /).count(), 0);
  await page.screenshot({ path: path.join(report, 'claim-approved-awaiting-payment.png'), fullPage: true });
  await page.getByTestId('claim-file-input').setInputFiles({ name: 'transfer-uji.pdf', mimeType: 'application/pdf', buffer: pdf });
  await page.getByTestId('claim-pay').click();
  await page.getByTestId('claim-detail-dialog').getByText('PAID', { exact: true }).first().waitFor();
  checks.push('claim approval waits for payment; payment with a transfer proof reaches PAID');
  assert.deepEqual(errors, [], 'No uncaught browser application errors');
  fs.writeFileSync(path.join(report, 'result.json'), JSON.stringify({ status: 'passed', checks, browser: await browser.version(), live_data_used: false }, null, 2));
  console.log('BROWSER PASSED: login/password gate, settings, individual document review and approval/payment. Synthetic data only.');
} catch (error) {
  fs.writeFileSync(path.join(report, 'result.json'), JSON.stringify({ status: 'failed', checks, error: error.message, live_data_used: false }, null, 2));
  throw error;
} finally {
  if (browser) await browser.close();
  if (running) await running.stop();
  fixture.cleanup();
}
